package org.example

fun main() {
    val a = 10
    val b = 20

    // Arithmetic Operators
    println("a + b = ${a + b}")
    println("a - b = ${a - b}")
    println("a * b = ${a * b}")
    println("b / a = ${b / a}")
    println("b % a = ${b % a}")

    println()
    // Comparison Operators
    println("a == b: ${a == b}")
    println("a != b: ${a != b}")
    println("a > b: ${a > b}")
    println("a < b: ${a < b}")
    println("a >= b: ${a >= b}")
    println("a <= b: ${a <= b}")
}